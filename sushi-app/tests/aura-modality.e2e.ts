import { expect, test } from '@playwright/test';

const tomorrow = new Date(Date.now() + 86_400_000);
const ymd = new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Seoul', year: 'numeric', month: '2-digit', day: '2-digit' }).format(tomorrow);
const dateLabel = new Intl.DateTimeFormat('ko-KR').format(tomorrow);
const iso = (time: string) => `${ymd}T${time}+09:00`;
const school = { id: 1, name: '가상고', currentStage: 'accepted', recommendedStage: 'accepted', freeForThreePlus: false };
const makeRound = (id: number, start: string, end: string, modality: string) => ({ id, schoolId: 1, schoolName: '가상고', progressStage: 'accepted', parentFreeForThreePlus: false, roundNumber: id, roundNumbers: [id], roundLabel: `${id}회차`, eventId: id, startTime: iso(start), endTime: iso(end), description: 'Zoom 온라인', attendanceStatus: 'scheduled', modality, reportRequired: true, hourlyRate: 30000, amount: 30000, paymentStatus: 'pending', seriesGroupId: 'synthetic', seriesIndex: id, targets: [{id, studentName: `합성${id}`, report: null}] });

test('모바일·키보드: 명시 저장과 재조회 배지, 안전한 복사 프리뷰', async ({ page }) => {
  await page.setViewportSize({width: 390, height: 844});
  let rows = [makeRound(1, '10:00:00', '11:00:00', 'unverified'), makeRound(2, '11:59:59', '12:30:00', 'remote'), makeRound(3, '12:00:00', '12:30:00', 'remote')];
  let saved: Record<string, unknown> | null = null;
  let stale = false;
  let patchCount = 0;
  await page.route('**/auth/isjwt?key=mainauth', route => route.fulfill({json: {sub:'1', data:{id:'1',name:'합성'},exp:9999999999}}));
  await page.route('**/api/personal/**', route => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith('/aura/schools')) return route.fulfill({json:[school]});
    if (path.endsWith('/aura/rounds')) return route.fulfill({json:rows});
    if (path.endsWith('/aura/rounds/1/modality-preview')) return route.fulfill({json:{scope:'following',roundState:'snapshot',rounds:rows}});
    if (path.endsWith('/aura/rounds/1') && route.request().method() === 'PATCH') {
      patchCount++;
      if (stale) return route.fulfill({status:409,json:{detail:{message:'변경 대상이 다릅니다',affectedRoundIds:[1,2,3]}}});
      saved = route.request().postDataJSON();
      rows = rows.map(r => ({...r,modality: String(saved?.modality)}));
      return route.fulfill({json:{...rows[0],affectedRoundIds:[1,2,3]}});
    }
    if (path.endsWith('/aura/rounds/1')) return route.fulfill({json:rows[0]});
    return route.fulfill({json:[]});
  });
  await page.goto('/personal-project/aura');
  await expect(page.locator('.round-row').first()).toBeVisible();
  await page.getByRole('button', {name:'＋ 새 회차'}).click();
  await expect(page.getByLabel(/진행 방식/)).toHaveValue('in_person');
  await page.getByLabel(/진행 방식/).selectOption('remote');
  await expect(page.getByLabel(/진행 방식/)).toHaveValue('remote');
  await page.getByRole('button', {name:'취소'}).click();
  const dateButton = page.getByRole('button', {name: `${dateLabel} 강의실 배정 요청문 만들기`});
  await dateButton.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('button', {name:'복사하기'})).toBeDisabled();
  await expect(page.getByText('진행 방식이 지정되지 않은 수업이 있습니다.', {exact:false})).toBeVisible();
  await page.getByRole('button', {name:'닫기'}).click();
  await expect(dateButton).toBeFocused();
  await page.locator('.slot.busy').first().focus(); await page.keyboard.press('Enter');
  await page.getByLabel('반복 일정 수정 범위').selectOption('following');
  await page.getByLabel(/진행 방식/).selectOption('in_person');
  await expect(page.getByRole('button', {name:'변경 대상 새로 확인'})).toHaveCount(0);
  await page.getByRole('button', {name:'일정 수정'}).click();
  await expect.poll(() => saved).toMatchObject({modality:'in_person',scope:'following',expected_round_ids:[1,2,3],expected_round_state:'snapshot'});
  expect(saved).not.toHaveProperty('start_time');
  expect(saved).not.toHaveProperty('end_time');
  await expect(page.locator('.round-row').first()).toContainText('대면');
  await dateButton.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('button', {name:'복사하기'})).toBeEnabled();
  await expect(page.getByRole('textbox', {name:'강의실 배정 요청문'})).toHaveValue(/위 일정의 강의실 배정 부탁드립니다/);
  await page.getByRole('button', {name:'닫기'}).click();
  rows = rows.map(r => r.id === 1 ? r : {...r, modality: 'remote'});
  await dateButton.focus(); await page.keyboard.press('Enter');
  await expect(page.getByRole('textbox', {name:'강의실 배정 요청문'})).toHaveValue(/합성2 \(비대면\)/);
  await expect(page.getByRole('textbox', {name:'강의실 배정 요청문'})).not.toHaveValue(/합성3/);
  await expect(page.getByText('복사 전용')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({path:'test-results/aura-modality-mobile.png',fullPage:true});
  await page.getByRole('button', {name:'닫기'}).click();
  stale = true;
  await page.locator('.slot.busy').first().focus(); await page.keyboard.press('Enter');
  await page.getByLabel('반복 일정 수정 범위').selectOption('following');
  await page.getByLabel(/진행 방식/).selectOption('remote');
  await expect(page.getByRole('button', {name:'변경 대상 새로 확인'})).toHaveCount(0);
  await page.getByRole('button', {name:'일정 수정'}).click();
  await expect(page.locator('.modal [role=alert]')).toContainText('변경 대상이 다릅니다');
  await expect(page.getByLabel(/진행 방식/)).toHaveValue('remote');
  await page.screenshot({path:'test-results/aura-edit-error-mobile.png',fullPage:true});
  expect(patchCount).toBe(2);
  stale = false;
  await page.getByRole('button', {name:'일정 수정'}).click();
  await expect(page.locator('form.modal')).toHaveCount(0);
  expect(patchCount).toBe(3);
  rows = rows.map(r => ({...r, modality: r.id === 1 ? 'in_person' : 'remote'}));
  await page.setViewportSize({width:1280,height:800});
  await dateButton.click();
  await expect(page.getByRole('textbox', {name:'강의실 배정 요청문'})).toHaveValue(/합성2 \(비대면\)/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.screenshot({path:'test-results/aura-modality-desktop.png',fullPage:true});
});
